const norm = (s) => String(s || "").toLowerCase().replace(/[^a-z0-9]/g, "");

export function mergeFaqs(faqs = []) {
  const base = Array.isArray(faqs) ? faqs : [];
  const seen = new Set(base.map((f) => norm(f.question)));
  const extra = EXTRA_FAQS.filter((f) => !seen.has(norm(f.question))).map((f, i) => ({ id: `extra-${i}`, published: true, ...f }));
  return [...base, ...extra];
}

export const withExtraFaqs = (site) => (site ? { ...site, faqs: mergeFaqs(site.faqs) } : site);
